def κοστος_εργαζομενου(αναθεση):
    """Συνολικό κόστος όλων των παραπεμπτικών ενός εργαζομένου."""
    return round(sum(
        ΤΙΜΕΣ.get(ex, 0.0)
        for παρ in αναθεση["παραπεμπτικα"]
        for ex in παρ["εξετασεις"]
    ), 2)


def κοστος_συνολο(αναθεσεις):
    """
    (συνολικό κόστος, ανάλυση ανά πρόγραμμα)

    Το "κοστος_ατομου" είναι η τυπική τιμή του προγράμματος (η συχνότερη),
    όχι του πρώτου ατόμου - αλλιώς μια εξαίρεση ακοής παραμόρφωνε όλη
    την ομάδα. Το "συνολο" αθροίζει τα πραγματικά ατομικά κόστη.
    """
    from collections import Counter

    ανα_προγραμμα = {}
    for α in αναθεσεις:
        ανα_προγραμμα.setdefault(α["προγραμμα"], []).append(
            κοστος_εργαζομενου(α))

    αναλυση = {}
    for πρ, τιμες in ανα_προγραμμα.items():
        τυπικη = Counter(τιμες).most_common(1)[0][0]
        αναλυση[πρ] = {
            "ατομα": len(τιμες),
            "κοστος_ατομου": τυπικη,
            "συνολο": round(sum(τιμες), 2),
            "εξαιρεσεις": sum(1 for τ in τιμες if τ != τυπικη),
        }
    συνολο = round(sum(m["συνολο"] for m in αναλυση.values()), 2)
    return συνολο, αναλυση
