"""
Έλεγχος συνέπειας του μοντέλου κόστους.

Επιβεβαιώνει ότι το άθροισμα των επιμέρους εξετάσεων που αναθέτουν οι
κανόνες ισούται με το αναμενόμενο κόστος κάθε προγράμματος - δηλαδή ότι
κανένας κανόνας δεν προσθέτει ή δεν παραλείπει εξέταση κατά λάθος.

Οι τιμές είναι ενδεικτικές (βλ. costs.py).
"""
from datetime import date

import costs
import rules

ΒΑΣΗ = 114.50          # κοινές εξετάσεις για όλους
ΟΦΘΑΛΜΟΣ_ΣΠΙΡΟ = 45.00
ΑΚΟΗ = 20.00

ΑΝΑΜΕΝΟΜΕΝΑ = {
    "Πρόγραμμα Β1 (50+)": ΒΑΣΗ + 13.00 + ΟΦΘΑΛΜΟΣ_ΣΠΙΡΟ,           # + PSA
    "Πρόγραμμα Α1 (50+)": ΒΑΣΗ + 13.00 + ΟΦΘΑΛΜΟΣ_ΣΠΙΡΟ + ΑΚΟΗ,
    "Πρόγραμμα Β (50+)": ΒΑΣΗ + 65.00 + ΟΦΘΑΛΜΟΣ_ΣΠΙΡΟ,            # PAP+μαστ+DEXA
    "Πρόγραμμα Α (50+)": ΒΑΣΗ + 65.00 + ΟΦΘΑΛΜΟΣ_ΣΠΙΡΟ + ΑΚΟΗ,
}

ΔΟΚΙΜΕΣ = [("ΑΝΔΡΑΣ", "ΓΡΑΦΕΙΑ"), ("ΑΝΔΡΑΣ", "ΠΑΡΑΓΩΓΗ"),
           ("ΓΥΝΑΙΚΑ", "ΓΡΑΦΕΙΑ"), ("ΓΥΝΑΙΚΑ", "ΠΑΡΑΓΩΓΗ")]

if __name__ == "__main__":
    print(f'{"Πρόγραμμα":22} {"Μοντέλο":>9} {"Αναμεν.":>9}')
    σφαλματα = 0
    for φυλο, χωρος in ΔΟΚΙΜΕΣ:
        α = rules.αναθεση(
            dict(αμ=0, επωνυμο="X", ονομα="Y", πατρωνυμο="", φυλο=φυλο,
                 ημ_γεννησης=date(1970, 1, 1), χωρος=χωρος),
            ημ_αναφορας=date(2026, 6, 1))
        κ = costs.κοστος_εργαζομενου(α)
        αν = ΑΝΑΜΕΝΟΜΕΝΑ[α["προγραμμα"]]
        οκ = abs(κ - αν) < 0.01
        σφαλματα += not οκ
        print(f'{α["προγραμμα"]:22} {κ:>9.2f} {αν:>9.2f}  '
              f'{"OK" if οκ else "ΔΙΑΦΟΡΑ"}')
    print("\nΌλοι οι έλεγχοι πέρασαν." if not σφαλματα
          else f"\n{σφαλματα} αποτυχίες.")
