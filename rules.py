"""
Κανόνες ανάθεσης προγράμματος check-up και παραπεμπτικών.

Τρεις μεταβλητές καθορίζουν τα πάντα:
  - φύλο (ΑΝΔΡΑΣ / ΓΥΝΑΙΚΑ)
  - ηλικία (υπολογίζεται από ημ. γέννησης)
  - χώρος εργασίας (ΠΑΡΑΓΩΓΗ -> Α / ΓΡΑΦΕΙΑ -> Β)
"""

from datetime import date

# --- Εξετάσεις ανά παραπεμπτικό -------------------------------------------

ΓΕΝΙΚΕΣ_ΒΑΣΙΚΕΣ = [
    "Γενική αίματος",
    "Γενική ούρων",
    "Σάκχαρο",
    "Ουρικό οξύ",
    "Ουρία",
    "SGOT",
    "SGPT",
    "HDL",
    "LDL",
    "Χοληστερίνη",
    "Τριγλυκερίδια",
    "HbsAg",
    "Ακτινογραφία θώρακος",
    "Καρδιολογική εξέταση",
    "Ηλεκτροκαρδιογράφημα",
    "U/S άνω & κάτω κοιλίας",
]

ΑΚΟΗΣ = ["Ω.Ρ.Λ. Εξέταση", "Έλεγχος Ακοής"]
ΟΦΘΑΛΜΩΝ = ["Οφθαλμολογική εξέταση"]
ΣΠΙΡΟΜΕΤΡΗΣΗΣ = ["Σπιρομέτρηση"]


def ηλικια(ημ_γεννησης, ημ_αναφορας=None):
    """Συμπληρωμένα έτη στην ημερομηνία αναφοράς."""
    ref = ημ_αναφορας or date.today()
    return ref.year - ημ_γεννησης.year - (
        (ref.month, ref.day) < (ημ_γεννησης.month, ημ_γεννησης.day)
    )


def κωδικος_προγραμματος(φυλο, ετη, χωρος):
    """π.χ. 'Πρόγραμμα Α1 (50+)'"""
    γραμμα = "Α" if χωρος == "ΠΑΡΑΓΩΓΗ" else "Β"

    if φυλο == "ΑΝΔΡΑΣ":
        ζωνη = "(50+)" if ετη >= 50 else "(<50)"
        return f"Πρόγραμμα {γραμμα}1 {ζωνη}"

    if ετη >= 50:
        ζωνη = "(50+)"
    elif ετη >= 40:
        ζωνη = "(40-49)"
    else:
        ζωνη = "(<40)"
    return f"Πρόγραμμα {γραμμα} {ζωνη}"


def κωδικος_γενικων(φυλο, ετη):
    """Ποια έκδοση του παραπεμπτικού 1 χρειάζεται."""
    if φυλο == "ΑΝΔΡΑΣ":
        return "1Α (50+)" if ετη >= 50 else "1Α"
    if ετη >= 50:
        return "1Γ (50+)"
    if ετη >= 40:
        return "1Γ (40-49)"
    return "1Γ (<40)"


def γενικες_εξετασεις(φυλο, ετη):
    """Βασικές + ό,τι προστίθεται λόγω φύλου/ηλικίας."""
    λιστα = list(ΓΕΝΙΚΕΣ_ΒΑΣΙΚΕΣ)
    if φυλο == "ΑΝΔΡΑΣ":
        if ετη >= 50:
            λιστα.append("PSA")
    else:
        λιστα.append("PAP test")
        if ετη >= 40:
            λιστα.append("Ψηφιακή μαστογραφία")
        if ετη >= 50:
            λιστα.append("Μέτρηση οστικής πυκνότητας (DEXA)")
    return λιστα


def παραπεμπτικα(φυλο, ετη, χωρος, εξαιρεση_ακοης=False):
    """Επιστρέφει λίστα από dicts: {κωδικος, τιτλος, εξετασεις}."""
    out = [{
        "κωδικος": κωδικος_γενικων(φυλο, ετη),
        "ειδος": "ΓΕΝΙΚΕΣ",
        "τιτλος": "Γενικές εξετάσεις",
        "εξετασεις": γενικες_εξετασεις(φυλο, ετη),
    }]

    if χωρος == "ΠΑΡΑΓΩΓΗ" and not εξαιρεση_ακοης:
        out.append({"κωδικος": "2", "ειδος": "ΑΚΟΗΣ",
                    "τιτλος": "Εξετάσεις ακοής", "εξετασεις": ΑΚΟΗΣ})

    out.append({"κωδικος": "3", "ειδος": "ΟΦΘΑΛΜΩΝ",
                "τιτλος": "Οφθαλμολογική εξέταση", "εξετασεις": ΟΦΘΑΛΜΩΝ})
    out.append({"κωδικος": "4", "ειδος": "ΣΠΙΡΟΜΕΤΡΗΣΗ",
                "τιτλος": "Σπιρομέτρηση", "εξετασεις": ΣΠΙΡΟΜΕΤΡΗΣΗΣ})
    return out


def αναθεση(εργαζομενος, ημ_αναφορας=None):
    """
    εργαζομενος: dict με κλειδιά
      αμ, επωνυμο, ονομα, πατρωνυμο, φυλο, ημ_γεννησης, χωρος, εξαιρεση_ακοης
    """
    ετη = ηλικια(εργαζομενος["ημ_γεννησης"], ημ_αναφορας)
    return {
        **εργαζομενος,
        "ετη": ετη,
        "προγραμμα": κωδικος_προγραμματος(
            εργαζομενος["φυλο"], ετη, εργαζομενος["χωρος"]),
        "παραπεμπτικα": παραπεμπτικα(
            εργαζομενος["φυλο"], ετη, εργαζομενος["χωρος"],
            εργαζομενος.get("εξαιρεση_ακοης", False)),
    }
