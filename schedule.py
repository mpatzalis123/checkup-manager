"""
Κανόνας συχνότητας check-up (φύλλο "Εξετασεις 2026"):
  < 40 ετών   -> κάθε 3 χρόνια
  40-49 ετών  -> κάθε 2 χρόνια
  >= 50 ετών  -> κάθε χρόνο
"""

from datetime import date

from rules import ηλικια


def περιοδος_ετων(ετη):
    if ετη >= 50:
        return 1
    if ετη >= 40:
        return 2
    return 3


def οφειλει_φετος(εργαζομενος, ετος=None, τελευταιο_checkup=None):
    """
    τελευταιο_checkup: έτος (int) της τελευταίας εξέτασης, ή None αν ποτέ.
    Επιστρέφει (True/False, αιτιολογία).
    """
    ετος = ετος or date.today().year
    ετη = ηλικια(εργαζομενος["ημ_γεννησης"], date(ετος, 12, 31))
    περ = περιοδος_ετων(ετη)

    if τελευταιο_checkup is None:
        return True, "δεν υπάρχει προηγούμενο check-up"

    διαφορα = ετος - τελευταιο_checkup
    if διαφορα >= περ:
        return True, f"πέρασαν {διαφορα} έτη (όριο: {περ})"
    return False, f"επόμενο το {τελευταιο_checkup + περ}"


def λιστα_ετους(εργαζομενοι, τελευταια, ετος=None):
    """
    εργαζομενοι: λίστα dicts με 'αμ' και 'ημ_γεννησης'
    τελευταια: dict {αμ: έτος τελευταίου check-up}
    """
    ετος = ετος or date.today().year
    οφειλουν, δεν_οφειλουν = [], []
    for ε in εργαζομενοι:
        ναι, λογος = οφειλει_φετος(ε, ετος, τελευταια.get(ε["αμ"]))
        (οφειλουν if ναι else δεν_οφειλουν).append({**ε, "αιτιολογια": λογος})
    return οφειλουν, δεν_οφειλουν
